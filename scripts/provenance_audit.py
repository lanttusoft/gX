#!/usr/bin/env python3
#opencode: provenance audit — every file under resources/ must be accounted for
#   by license/provenance.json (author / AI-generated / public-domain /
#   third-party with terms), quarantined paths must stay untracked and
#   gitignored, denied names/hashes may not reappear, and license/ATTRIBUTIONS.md
#   is regenerated from the manifest. Purpose: bookkeeping for distribution
#   decisions (what may ship, what needs attribution, what must be replaced),
#   not access policing.
#
#   Usage:
#     python3 scripts/provenance_audit.py            # report
#     python3 scripts/provenance_audit.py --strict   # exit 1 on any issue

import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
from pathlib import Path


PROJECT = Path(__file__).resolve().parent.parent
RESOURCES = PROJECT / "resources"
MANIFEST = PROJECT / "license" / "provenance.json"
ATTRIBUTIONS = PROJECT / "license" / "ATTRIBUTIONS.md"


def glob_regex(pattern):
    """Glob with ** (any path) and * (within a segment) semantics."""
    parts = []
    index = 0
    while index < len(pattern):
        char = pattern[index]
        if char == "*":
            if index + 1 < len(pattern) and pattern[index + 1] == "*":
                parts.append(".*")
                index += 2
                continue
            parts.append("[^/]*")
        elif char == "?":
            parts.append("[^/]")
        else:
            parts.append(re.escape(char))
        index += 1
    return re.compile("^" + "".join(parts) + "$")


def git_lines(*arguments):
    result = subprocess.run(["git", *arguments], cwd=PROJECT,
                            stdout=subprocess.PIPE, check=True)
    return result.stdout.decode()


def git_tracked():
    #ai: source tarballs have no .git; provenance entries are still checked,
    #    but tracked/ignored quarantine checks are only meaningful in a checkout.
    try:
        return {path for path in git_lines("ls-files", "-z").split("\0") if path}
    except (OSError, subprocess.CalledProcessError):
        return set()


def git_ignored(relative):
    try:
        result = subprocess.run(["git", "check-ignore", "-q", relative],
            cwd=PROJECT)
        return result.returncode == 0
    except OSError:
        return False


def sha256(path):
    digest = hashlib.sha256()
    with open(path, "rb") as stream:
        for block in iter(lambda: stream.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def write_attributions(manifest):
    lines = [
        "# gX — Attributions",
        "",
        "<!-- generated by scripts/provenance_audit.py from license/provenance.json -->",
        "",
        "## Shipped third-party content",
        "",
    ]
    for entry in manifest["entries"]:
        if entry["origin"] != "third-party" or entry["publish"] == "quarantine":
            continue
        line = f"- `{entry['match']}` — {entry['license']}"
        if entry.get("attribution"):
            line += f" — {entry['attribution']}"
        lines.append(line)
    if manifest.get("quarantine"):
        lines += ["", "## Quarantined (present locally, never committed)", ""]
        for path in manifest.get("quarantine", []):
            lines.append(f"- `{path}`")
    actions = [entry for entry in manifest["entries"] if entry["publish"] != "keep"]
    if actions:
        lines += ["", "## Publish actions", ""]
        for entry in actions:
            lines.append(f"- `{entry['match']}` — {entry['publish']}")
    ATTRIBUTIONS.write_text("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--strict", action="store_true")
    arguments = parser.parse_args()
    if not MANIFEST.is_file():
        print("provenance audit: manifest missing", file=sys.stderr)
        return 1
    manifest = json.loads(MANIFEST.read_text())
    compiled = [(entry, glob_regex(entry["match"]))
                for entry in manifest["entries"]]
    quarantine = set(manifest.get("quarantine", []))
    tracked = git_tracked()
    issues = []

    for root, directories, files in os.walk(RESOURCES):
        directories[:] = [name for name in directories if name != "__pycache__"]
        for name in files:
            relative = (Path(root) / name).relative_to(PROJECT).as_posix()
            if relative in quarantine:
                if relative in tracked:
                    issues.append(f"{relative}: quarantined but still tracked")
                if not git_ignored(relative):
                    issues.append(f"{relative}: quarantined but not gitignored")
                continue
            if not any(regex.match(relative) for _, regex in compiled):
                issues.append(f"{relative}: no provenance entry "
                              "(add one to license/provenance.json)")

    for rule in manifest.get("denied", []):
        for relative in sorted(tracked):
            if not relative.startswith("resources/"):
                continue
            if rule.get("name") and rule["name"].lower() in os.path.basename(
                    relative).lower():
                issues.append(f"{relative}: denied name '{rule['name']}' "
                              f"({rule.get('reason', '')})")
            if rule.get("sha256"):
                full = PROJECT / relative
                if full.is_file() and sha256(full) == rule["sha256"]:
                    issues.append(f"{relative}: denied content hash "
                                  f"({rule.get('reason', '')})")

    write_attributions(manifest)
    print(f"provenance audit: {len(compiled)} entries, "
          f"{len(quarantine)} quarantined paths, {len(issues)} issue(s)")
    for issue in issues:
        print(f"  [PROVENANCE] {issue}")
    print(f"provenance audit: {'CLEAN' if not issues else 'ISSUES'}")
    if issues and arguments.strict:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
