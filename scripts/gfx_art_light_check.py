#!/usr/bin/env python3
#opencode: original-art editor regression for point-shadow ownership on light
#   removal and heap-slot reuse, driven through GX_AI_INPUT.

import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile

import numpy as np
from PIL import Image

import audit_common as audit


ROOT = audit.ROOT
BIN = audit.BIN
PRESET = ROOT / "resources" / "tools" / "art.json"
SHADOW_DELETE_ERROR = re.compile(
    r"GL_DEBUG \[HIGH\].*GL_INVALID_OPERATION.*"
    r"Texture name does not refer to a texture object generated by OpenGL\."
)
REMOVE_INPUT = (
    "1.0 move 1600 205 300;1.5 click 1600 205;"
    "2.0 move 1500 493 300;2.5 click 1500 493;"
    "3.0 move 1560 452 300;3.5 click 1560 452"
)
REUSE_INPUT = REMOVE_INPUT + ";4.0 move 1465 452 300;4.5 click 1465 452"


def capture(temp_root, name, frame, input_script=None):
    directory = temp_root / name
    directory.mkdir(parents=True, exist_ok=True)
    environment = audit.scene_env({
        "GX_FIXED_DT": "0.0166666667",
        "GX_GFX_PRESET_LOAD": str(PRESET),
    }, clean=True)
    if input_script:
        environment["GX_AI_INPUT"] = input_script
    try:
        with audit.settings_preserved():
            result = audit.run_scene(
                "--gfx", environment, width=1536, height=1016,
                fps=None, shot_frame=frame, screenshot_dir=directory,
                timeout=120, check=False, extra_args=("--gfx-editor",))
    except subprocess.TimeoutExpired as error:
        output = error.stdout or ""
        if isinstance(output, bytes):
            output = output.decode(errors="replace")
        raise RuntimeError(f"{name}: timed out\n{output[-3000:]}") from error
    if result.returncode != 0:
        raise RuntimeError(f"{name}: process failed ({result.returncode})\n{result.stdout[-3000:]}")
    if SHADOW_DELETE_ERROR.search(result.stdout):
        raise RuntimeError(f"{name}: shared point-shadow resource was invalidated\n{result.stdout[-3000:]}")
    screenshots = list(directory.glob("gXss_*.png"))
    if not screenshots:
        raise RuntimeError(f"{name}: screenshot missing\n{result.stdout[-3000:]}")
    screenshot = max(screenshots, key=lambda path: path.stat().st_mtime)
    pixels = np.asarray(Image.open(screenshot).convert("RGB"), dtype=np.int16)
    return result.stdout, pixels


def require_visible_change(label, first, second):
    if first.shape != second.shape:
        raise RuntimeError(f"{label}: capture sizes differ: {first.shape} vs {second.shape}")
    height, width = first.shape[:2]
    region = (slice(int(height * 0.025), height),
              slice(int(width * 0.177), int(width * 0.79)))
    delta = np.abs(first[region] - second[region])
    mean = float(delta.mean())
    changed = float((delta > 2).any(axis=2).mean())
    if mean < 0.25 or changed < 0.005:
        raise RuntimeError(
            f"{label}: expected visible light response, mean={mean:.4f}, "
            f"pixels={changed:.3%}"
        )
    print(f"  {label}: mean={mean:.3f}, changed={changed:.2%}")


def main():
    if not BIN.is_file():
        print(f"GFX_ART_LIGHT_CHECK: binary missing: {BIN}", file=sys.stderr)
        return 1
    if not PRESET.is_file():
        print(f"GFX_ART_LIGHT_CHECK: original art preset missing: {PRESET}", file=sys.stderr)
        return 1
    os.makedirs("/tmp/opencode", exist_ok=True)
    try:
        with tempfile.TemporaryDirectory(prefix="gfx_art_light_", dir="/tmp/opencode") as temporary:
            temp_root = Path(temporary)
            baseline_log, baseline = capture(temp_root, "baseline", 300)
            if "point shadow array created:" not in baseline_log:
                raise RuntimeError("baseline did not initialize the shared point-shadow array")
            removed_log, removed = capture(temp_root, "removed", 300, REMOVE_INPUT)
            if "GfxEd: light 0 removed" not in removed_log:
                raise RuntimeError("editor did not remove original-art light slot 0")
            reused_log, reused = capture(temp_root, "reused", 360, REUSE_INPUT)
            if "GfxEd: light 0 removed" not in reused_log:
                raise RuntimeError("slot-reuse run did not remove original-art light slot 0")
            if "GfxEd: light added at 0" not in reused_log:
                raise RuntimeError("replacement light did not reuse heap slot 0")
            print("GFX_ART_LIGHT_CHECK: original-art light contribution and slot reuse")
            require_visible_change("light removal", baseline, removed)
            require_visible_change("slot-0 replacement", removed, reused)
    except (OSError, RuntimeError, subprocess.SubprocessError) as error:
        print(f"GFX_ART_LIGHT_CHECK: FAIL: {error}", file=sys.stderr)
        return 1
    print("GFX_ART_LIGHT_CHECK: PASS")
    return 0


if __name__ == "__main__":
    sys.exit(main())
