#!/usr/bin/env python3
"""
Generate docs/gfx_shader_inventory.md from resources/shader/.

Groups shader sources by directory and extension, with a running count.
Skips compiled .bin cache files (listed separately). Run:
    python3 scripts/gen_shader_inventory.py
"""
import os
import sys

PROJECT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHADER_DIR = os.path.join(PROJECT, "resources", "shader")
OUT = os.path.join(PROJECT, "docs", "gfx_shader_inventory.md")

SRC_EXT = (".frag", ".vert", ".geom", ".glsl")
BIN_EXT = ".bin"

CATEGORIES = {
    "": "Root — engine / renderer / scene shaders",
    "common": "Shared GLSL snippets (included via the shader preprocessor)",
    "gui": "GUI canvas element shaders (test + lens)",
    "postprocess": "Post-process effect chain (~54 effects)",
    "raymarch": "SDF raymarching — historical iterations + current",
}


def main():
    files = {}
    bins = []
    for root, _dirs, names in os.walk(SHADER_DIR):
        rel_dir = os.path.relpath(root, SHADER_DIR)
        for n in sorted(names):
            rel = os.path.relpath(os.path.join(root, n), SHADER_DIR)
            if n.endswith(BIN_EXT):
                bins.append(rel)
            elif n.endswith(SRC_EXT):
                files.setdefault(rel_dir, []).append(n)

    total = sum(len(v) for v in files.values())
    lines = []
    lines.append("GFX Shader Inventory — Documentation")
    lines.append("======================================")
    lines.append("//opencode: generated by scripts/gen_shader_inventory.py —")
    lines.append("//   do not edit by hand; re-run the script to regenerate.")
    lines.append("")
    lines.append(f"Total shader source files: {total} across {len(files)} directories.")
    lines.append("")
    lines.append("Texture unit budget (see src/renderer/gfx/constants.h): units ≤ 31 "
                 "(GL_MAX_TEXTURE_IMAGE_UNITS = 32).")
    lines.append("")

    for dirname in sorted(files):
        label = CATEGORIES.get(dirname)
        if label is None:
            label = CATEGORIES.get("") if dirname in (".", "") else dirname
        display = "root" if dirname in (".", "") else dirname
        lines.append(f"{display}/ — {label}")
        lines.append("  " + "-" * max(10, len(label)))
        # count by extension
        by_ext = {}
        for f in files[dirname]:
            e = f.rsplit(".", 1)[-1]
            by_ext[e] = by_ext.get(e, 0) + 1
        ext_summary = ", ".join(f"{e}×{by_ext[e]}" for e in sorted(by_ext))
        lines.append(f"  Files: {ext_summary}")
        for f in files[dirname]:
            lines.append(f"    {f}")
        lines.append("")

    if bins:
        lines.append(f"Compiled shader cache (.bin) — {len(bins)} files:")
        lines.append("  Stale cache artifacts from raylib's program-binary cache;")
        lines.append("  safe to delete (regenerated on load). Roadmap N9.3.")
        for b in bins:
            lines.append(f"    {b}")
        lines.append("")

    with open(OUT, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"Wrote {OUT} ({total} shader files, {len(bins)} bin caches)")


if __name__ == "__main__":
    sys.exit(main())
