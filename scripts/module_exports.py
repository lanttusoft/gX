#opencode: generate modules/module_exports.txt — the Route A module ABI
#   surface (docs/dynamic_modules.md): the module's undefined symbols
#   intersected with the exe's global defined symbols. The list is checked in
#   and treated as append-only within GX_MODULE_ABI_VERSION; the module check
#   gate runs --check to catch drift (regenerate with `make module-exports`).
#
#   Usage:
#     python3 scripts/module_exports.py <exe-objdir|exe> <module.so> [out.txt]
#     python3 scripts/module_exports.py --check <exe-objdir|exe> <module.so> [out.txt]

import argparse
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUT = ROOT / "modules" / "module_exports.txt"

HEADER = """\
/* gX dynamic module exports (Route A ABI) — generated by
 * scripts/module_exports.py from the module targets' undefined symbols.
 * APPEND-ONLY within GX_MODULE_ABI_VERSION (docs/dynamic_modules.md);
 * regenerate with `make module-exports`.
 */
{
"""


def nm_names(path, undefined):
    flag = "--undefined-only" if undefined else "--defined-only"
    args = ["nm", flag, "--format=posix"]
    if not undefined:
        args.append("--extern-only")
    result = subprocess.run(args + [str(path)], capture_output=True, text=True)
    if result.returncode != 0:
        print(result.stderr.strip(), file=sys.stderr)
        raise SystemExit(2)
    names = []
    for line in result.stdout.splitlines():
        parts = line.split()
        if len(parts) < 2:
            continue
        name, kind = parts[0], parts[1]
        if undefined:
            if kind != "U":
                continue
        elif kind == "U":
            continue
        names.append(name)
    return set(names)


def defined_universe(exe):
    #opencode: the exe LINKED is post-gc-sections — engine APIs the shell
    #   needs may already be dropped. The honest "exe can define this" set is
    #   the union over its object files, so the generated list forces those
    #   symbols to stay (dynamic-list entries are GC roots).
    if exe.is_dir():
        objs = sorted(exe.rglob("*.o"))
        if not objs:
            raise SystemExit(f"module_exports: no objects under {exe}")
        universe = set()
        for obj in objs:
            universe |= nm_names(obj, undefined=False)
        return universe
    return nm_names(exe, undefined=False)


def render(exe, modules):
    undefined = set()
    for module in modules:
        undefined |= nm_names(module, undefined=True)
    defined = defined_universe(exe)
    needed = sorted(undefined & defined)
    if not needed:
        raise SystemExit("module_exports: empty export set — check the inputs")
    return HEADER + "".join("    %s;\n" % s for s in needed) + "};\n"


def parse_exports(text):
    symbols = set()
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith(("/*", "*", "{", "}")):
            continue
        if line.endswith(";"):
            line = line[:-1].strip()
        if line:
            symbols.add(line)
    return symbols


def main():
    parser = argparse.ArgumentParser(description="gX module export list tool")
    parser.add_argument("--check", action="store_true",
                        help="verify the on-disk list matches a fresh generation")
    parser.add_argument("exe", type=Path,
                        help="exe object dir (preferred) or the linked exe")
    parser.add_argument("modules", type=Path, nargs="+")
    parser.add_argument("out", type=Path, nargs="?", default=DEFAULT_OUT)
    args = parser.parse_args()

    for path in (args.exe, *args.modules):
        if not path.exists():
            print(f"module_exports: missing {path}", file=sys.stderr)
            return 2

    content = render(args.exe, args.modules)
    needed = parse_exports(content)

    if args.check:
        existing_text = args.out.read_text() if args.out.is_file() else ""
        existing = parse_exports(existing_text)
        missing = sorted(needed - existing)
        if missing:
            print("MODULE_EXPORTS: STALE — run 'make module-exports' "
                  f"({len(missing)} needed symbols missing, e.g. "
                  f"{', '.join(missing[:5])})", file=sys.stderr)
            return 1
        print(f"module_exports: OK ({len(needed)} needed, "
              f"{len(existing)} exported; append-only extras allowed)")
        return 0

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(content)
    print(f"module_exports: wrote {args.out} ({content.count(';')} symbols)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
